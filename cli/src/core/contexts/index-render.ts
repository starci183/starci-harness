import { readFileSync, readdirSync, statSync } from "node:fs"
import { join, relative } from "node:path"
import { ruleIdsIn } from "../../harness/contract.js"
import { SLICE_EDITIONS, SLICE_SIDES, sliceFile } from "./anatomy-render.js"
import { SECTIONED_DOCS } from "./sectioned-docs.js"

/** The index's place under contexts/: beside the project map, linking every other file of the tree. */
export const INDEX_FILE = "project/index.md"

/** The marker the generated index carries: the whole file is generated. */
export const INDEX_MARKER = "<!-- generated by `starci contexts anatomy --execute` from every file of contexts/; do not edit -->"

// An index line stays one line: a summary longer than this is cut at a word.
const SUMMARY_CHARS = 180

// A data file may name hundreds of ids; the index lists the first ones and counts the rest.
const IDS_SHOWN = 24

const byCodeUnit = (left: string, right: string): number => Number(left > right) - Number(left < right)

/** Every Markdown and yaml file under `dir`, relative with forward slashes, in code-unit order. */
const treeFiles = (dir: string): string[] =>
    readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile() && /\.(md|ya?ml)$/.test(entry.name))
        .map((entry) => relative(dir, join(entry.parentPath, entry.name)).replaceAll("\\", "/"))
        .sort(byCodeUnit)

const plain = (text: string): string =>
    text
        .replace(/\[([^\][]*)\]\([^()]*\)/g, "$1")
        .replace(/\s+/g, " ")
        .trim()

const cut = (text: string): string => {
    // The first `.`, `!` or `?` past the first character that ends the text or comes before a blank closes the sentence.
    const end = text.slice(1).search(/[.!?](?:\s|$)/)
    const sentence = end === -1 ? text : text.slice(0, end + 2)
    if (sentence.length <= SUMMARY_CHARS) return sentence
    const head = sentence.slice(0, SUMMARY_CHARS)
    return `${head.slice(0, Math.max(head.lastIndexOf(" "), SUMMARY_CHARS / 2)).trimEnd()} ...`
}

/** The first sentence of a Markdown file's first paragraph after its front matter and title; a table, list or fence ends the search. */
export const markdownSummary = (lines: readonly string[]): string => {
    const start = lines[0] === "---" ? lines.indexOf("---", 1) + 1 : 0
    const paragraph: string[] = []
    for (const line of lines.slice(start)) {
        const trimmed = line.trim()
        if (paragraph.length === 0 && (trimmed === "" || trimmed.startsWith("#") || trimmed.startsWith("<!--"))) continue
        if (trimmed === "" || /^(#|\||```|- |\* |\d+\. )/.test(trimmed)) break
        paragraph.push(trimmed)
    }
    return cut(plain(paragraph.join(" ")))
}

/** A yaml file's leading comment, else its schema tag. */
const yamlSummary = (lines: readonly string[]): string => {
    const comment = lines.filter((line, index) => line.startsWith("#") && lines.slice(0, index).every((before) => before.startsWith("#"))).map((line) => line.replace(/^#\s?/, ""))
    if (comment.length > 0) return cut(plain(comment.join(" ")))
    const schema = lines.find((line) => line.startsWith("schema:"))
    return schema === undefined ? "data" : `data, ${schema.replace(/^schema:\s*/, "")}`
}

const SECTION = /^##\s+(\S.*)$/

const listed = (ids: readonly string[]): string => {
    const more = ids.length > IDS_SHOWN ? ` and ${String(ids.length - IDS_SHOWN)} more` : ""
    return ids.slice(0, IDS_SHOWN).join(", ") + more
}

/** One entry of the index: the file with its size and summary, then its sections and the ids it names. */
const entryOf = (contexts: string, path: string): string[] => {
    const file = join(contexts, path)
    const lines = readFileSync(file, "utf8").replaceAll("\r\n", "\n").split("\n")
    const markdown = path.endsWith(".md")
    const kb = Math.max(1, Math.round(statSync(file).size / 1024))
    const summary = markdown ? markdownSummary(lines) : yamlSummary(lines)
    const sections = markdown ? lines.flatMap((line) => SECTION.exec(line)?.[1]?.trim() ?? []).map(plain) : []
    // A heading's ids already show in its section; the ids line names the others (a yaml `id:`, a deeper heading).
    const headed = new Set(sections.flatMap((section) => section.split(/[^A-Za-z0-9._-]+/)))
    const ids = [...ruleIdsIn(lines.join("\n"))].filter((id) => !headed.has(id)).sort(byCodeUnit)
    const summaryNote = summary === "" ? "" : " — " + summary
    return [
        `- [${path}](../${path}) · ${String(kb)} KB${summaryNote}`,
        ...(sections.length === 0 ? [] : [`  - sections: ${sections.join(" · ")}`]),
        ...(ids.length === 0 ? [] : [`  - ids: ${listed(ids)}`]),
    ]
}

/**
 * The generated files of contexts/ that repeat another file, relative to contexts/: this index, the anatomy slices (which
 * repeat anatomy.md) and the section indexes (each repeating its SECTIONED_DOCS source). Neither the index nor the search corpus lists them.
 */
export const repeatingFiles = (): Set<string> => new Set([INDEX_FILE, ...SECTIONED_DOCS.map((doc) => doc.index), ...SLICE_EDITIONS.flatMap((edition) => SLICE_SIDES.map((side) => `project/${sliceFile(edition, side)}`))])

/**
 * The contexts index: every file of the tree with its size, a one-line summary, its sections and the rule or record ids it
 * names. A Kernel reads it instead of the whole tree, then opens only the files its tasks need.
 */
export const renderIndex = (contexts: string): string => {
    const skipped = repeatingFiles()
    const files = treeFiles(contexts).filter((path) => !skipped.has(path))
    const lines = [
        "# Contexts index",
        "",
        INDEX_MARKER,
        "",
        "Every file of `contexts/` with its size, the first sentence it opens with, its sections and the ids it names. A Kernel",
        "reads this index instead of the whole tree, then opens only the files its tasks need and names them in each contract.",
        "",
        ...files.flatMap((path) => entryOf(contexts, path)),
    ]
    return `${lines.join("\n")}\n`
}
