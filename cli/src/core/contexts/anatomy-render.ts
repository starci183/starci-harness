import { readFileSync, readdirSync } from "node:fs"
import { join } from "node:path"
import { parse } from "yaml"
import { z } from "zod"
import { Refusal } from "../../shared/errors.js"

const presenceSchema = z.enum(["required", "optional", "opt-in", "forbidden"])
type Presence = z.infer<typeof presenceSchema>

const slotSchema = z.object({
    id: z.string(),
    profiles: z.array(z.enum(["app", "be", "fe"])),
    path: z.string(),
    presence: presenceSchema,
    litePresence: z.union([presenceSchema, z.record(z.string(), presenceSchema)]).optional(),
    tracked: z.enum(["tracked", "ignored", "external"]),
    editions: z.array(z.enum(["lite", "full"])).optional(),
    rules: z.array(z.string()).optional(),
})
type Slot = z.infer<typeof slotSchema>

const ruleSchema = z.object({
    id: z.string(),
    code: z.string(),
    failureCodes: z.array(z.string()).optional(),
    enforcers: z.array(z.object({ kind: z.string(), id: z.string() })).optional(),
})
type Rule = z.infer<typeof ruleSchema>

const frontMatterSchema = z.object({
    slots: z.array(z.string()).optional(),
    files: z.array(z.object({ slot: z.string().optional() })).optional(),
})

/** The editions and sides the anatomy is rendered for, in this order. */
const EDITIONS = ["lite", "full"] as const
type AnatomyEdition = (typeof EDITIONS)[number]
const SIDES = ["app", "be", "fe"] as const
type Side = (typeof SIDES)[number]

/** Enforcer kinds that judge the other side only; a tree hides them so each line names the lint of its own side. */
const FOREIGN_KINDS: Readonly<Record<Side, readonly string[]>> = {
    app: [],
    be: ["eslint-fe", "eslint-grammar-starci", "stylelint"],
    fe: ["eslint-be"],
}

/** Opening marker of the generated block in contexts/project/anatomy.md. */
export const BEGIN_MARKER = "<!-- anatomy:begin (generated by `starci contexts anatomy --write` from hfs/slots.yaml; do not edit) -->"
/** Closing marker of the generated block. */
export const END_MARKER = "<!-- anatomy:end -->"

/** The rendered block and the slot rule codes that resolve to no rule of hfs/rules.yaml. */
export interface AnatomyRender {
    readonly block: string
    readonly dangling: readonly string[]
}

interface Node {
    label: string
    readonly children: Map<string, Node>
    readonly slots: Slot[]
}

interface Sources {
    readonly slots: readonly Slot[]
    readonly rules: readonly Rule[]
    readonly patterns: Topics
}

/** Pattern topics per slot id: `declared` from the front matter `slots`, `files` from the slot of each `files` entry. */
interface Topics {
    readonly declared: ReadonlyMap<string, readonly string[]>
    readonly files: ReadonlyMap<string, readonly string[]>
}

const addTo = (map: Map<string, string[]>, id: string, topic: string): void => {
    const list = map.get(id) ?? []
    if (!list.includes(topic)) map.set(id, [...list, topic])
}

const parseYaml = (file: string, text: string): unknown => {
    try {
        return parse(text)
    } catch (error: unknown) {
        throw new Refusal("KNOWLEDGE_INVALID", `${file} is not readable yaml: ${error instanceof Error ? error.message : String(error)}`)
    }
}

const readYaml = (file: string): unknown => parseYaml(file, readFileSync(file, "utf8"))

const parsed = <T>(file: string, value: unknown, schema: z.ZodType<T>): T => {
    const result = schema.safeParse(value)
    if (!result.success) throw new Refusal("KNOWLEDGE_INVALID", `${file} is invalid: ${z.prettifyError(result.error)}`)
    return result.data
}

/** Code-unit order, so a generated block does not depend on the locale of the machine that renders it. */
const byCodeUnit = (left: string, right: string): number => Number(left > right) - Number(left < right)

/** The front matter of one pattern topic file, or undefined when the file has none. */
const readFrontMatter = (file: string) => {
    const text = readFileSync(file, "utf8").replaceAll("\r\n", "\n")
    const match = /^---\n([\s\S]*?)\n---\n/.exec(text)
    return match?.[1] === undefined ? undefined : parsed(file, parseYaml(file, match[1]), frontMatterSchema)
}

/** Reads the front matter of every pattern topic into the slot ids (or family prefixes) it declares and the slots its files land in. */
const readPatterns = (knowledge: string): Topics => {
    const declared = new Map<string, string[]>()
    const files = new Map<string, string[]>()
    for (const side of ["be", "fe"]) {
        const folder = join(knowledge, "code", side)
        for (const name of readdirSync(folder).filter((file) => file.endsWith(".md")).sort(byCodeUnit)) {
            const front = readFrontMatter(join(folder, name))
            if (front === undefined) continue
            const topic = `${side}/${name}`
            for (const id of front.slots ?? []) addTo(declared, id, topic)
            for (const slot of (front.files ?? []).map((entry) => entry.slot)) if (slot !== undefined) addTo(files, slot, topic)
        }
    }
    return { declared, files }
}

const readSources = (knowledge: string): Sources => {
    const slotsFile = join(knowledge, "hfs", "slots.yaml")
    const rulesFile = join(knowledge, "hfs", "rules.yaml")
    return {
        slots: parsed(slotsFile, readYaml(slotsFile), z.object({ slots: z.array(slotSchema) })).slots,
        rules: parsed(rulesFile, readYaml(rulesFile), z.object({ rules: z.array(ruleSchema) })).rules,
        patterns: readPatterns(knowledge),
    }
}

/** The presence of a slot in one edition and side, or undefined when the slot does not exist there. */
const presenceIn = (slot: Slot, edition: AnatomyEdition, side: Side): Presence | undefined => {
    if (slot.editions !== undefined && !slot.editions.includes(edition)) return undefined
    if (edition === "lite" && slot.litePresence !== undefined) {
        return typeof slot.litePresence === "string" ? slot.litePresence : (slot.litePresence[side] ?? slot.presence)
    }
    return slot.presence
}

/** Splits a slot path on `/` outside braces; each directory segment keeps its trailing `/`. */
const segmentsOf = (path: string): string[] => {
    const segments: string[] = []
    let depth = 0
    let current = ""
    for (const char of path) {
        if (char === "{") depth += 1
        if (char === "}") depth -= 1
        current += char
        if (char === "/" && depth === 0) {
            segments.push(current)
            current = ""
        }
    }
    if (current !== "") segments.push(current)
    return segments
}

const newNode = (label: string): Node => ({ label, children: new Map(), slots: [] })

const buildTree = (slots: readonly Slot[]): Node => {
    const root = newNode("")
    for (const slot of slots) {
        let node = root
        for (const segment of segmentsOf(slot.path)) {
            const next = node.children.get(segment) ?? newNode(segment)
            node.children.set(segment, next)
            node = next
        }
        node.slots.push(slot)
    }
    return root
}

/** Folds a chain of directories that hold no slot into one label (`apps/<app>/src/`). */
const collapse = (node: Node): Node => {
    for (const [key, child] of node.children) node.children.set(key, collapse(child))
    const only = node.children.size === 1 ? [...node.children.values()][0] : undefined
    if (only !== undefined && node.slots.length === 0 && node.label !== "") {
        return { label: node.label + only.label, children: only.children, slots: only.slots }
    }
    return node
}

const escapeRegex = (part: string): string => part.replace(/[.+?^${}()|[\]\\]/g, String.raw`\$&`)

const codeMatcher = (code: string): RegExp => {
    const body = code.split("*").map(escapeRegex).join(".*")
    return new RegExp("^" + body + "$")
}

const rulesOf = (slot: Slot, rules: readonly Rule[], dangling: Set<string>): Rule[] => {
    const found: Rule[] = []
    for (const code of slot.rules ?? []) {
        const matcher = codeMatcher(code)
        const matches = rules.filter((rule) => matcher.test(rule.code) || (rule.failureCodes ?? []).some((failure) => matcher.test(failure)))
        if (matches.length === 0) dangling.add(code)
        for (const rule of matches) if (!found.includes(rule)) found.push(rule)
    }
    return found
}

const renderRule = (rule: Rule, side: Side): string => {
    const byKind = new Map<string, string[]>()
    for (const enforcer of rule.enforcers ?? []) {
        if (FOREIGN_KINDS[side].includes(enforcer.kind)) continue
        byKind.set(enforcer.kind, [...(byKind.get(enforcer.kind) ?? []), `\`${enforcer.id}\``])
    }
    const enforcers = [...byKind].map(([kind, ids]) => `${kind} ${ids.join(" ")}`).join("; ")
    return enforcers === "" ? rule.id : `${rule.id} (${enforcers})`
}

/**
 * The topics of a slot: those declaring its id or a family prefix that is no slot itself (`be.app` for `be.app.api`); a slot
 * no topic declares falls back to the topics whose `files` land in it. A side tree keeps the topics of its own side.
 */
const patternsOf = (slot: Slot, side: Side, sources: Sources): string[] => {
    const files: string[] = []
    for (const [prefix, owners] of sources.patterns.declared) {
        const family = !sources.slots.some((other) => other.id === prefix) && slot.id.startsWith(`${prefix}.`)
        if (slot.id !== prefix && !family) continue
        for (const owner of owners) if (!files.includes(owner)) files.push(owner)
    }
    if (files.length === 0) files.push(...(sources.patterns.files.get(slot.id) ?? []))
    const ofSide = side === "app" ? files : files.filter((file) => file.startsWith(`${side}/`))
    ofSide.sort(byCodeUnit)
    return ofSide.map((file) => `[${file.replace(/\.md$/, "")}](../code/${file})`)
}

const renderSlot = (slot: Slot, presence: Presence, side: Side, sources: Sources, dangling: Set<string>): string => {
    const parts = [`**${slot.id}** ${presence}`]
    const patterns = patternsOf(slot, side, sources)
    if (patterns.length > 0) parts.push(patterns.join(", "))
    const rules = rulesOf(slot, sources.rules, dangling).map((rule) => renderRule(rule, side))
    const unresolved = (slot.rules ?? []).filter((code) => dangling.has(code)).map((code) => `${code} (no rule)`)
    if (rules.length + unresolved.length > 0) parts.push([...rules, ...unresolved].join(", "))
    return parts.join(" · ")
}

const renderNode = (node: Node, depth: number, context: { readonly lines: string[]; readonly line: (slot: Slot) => string }): void => {
    const indent = "  ".repeat(depth)
    const [first, ...rest] = node.slots
    const head = `${indent}- \`${node.label}\``
    context.lines.push(first !== undefined && rest.length === 0 ? `${head} — ${context.line(first)}` : head)
    if (rest.length > 0) for (const slot of node.slots) context.lines.push(`${indent}  - ${context.line(slot)}`)
    for (const child of node.children.values()) renderNode(child, depth + 1, context)
}

const renderTree = (edition: AnatomyEdition, side: Side, sources: Sources, dangling: Set<string>): string[] => {
    const present = sources.slots.flatMap((slot) => {
        const presence = slot.profiles.includes(side) ? presenceIn(slot, edition, side) : undefined
        return presence === undefined ? [] : [{ slot, presence }]
    })
    const shown = present.filter((entry) => entry.presence !== "forbidden" && entry.slot.tracked === "tracked")
    const presenceOf = new Map(shown.map((entry) => [entry.slot.id, entry.presence]))
    const where = side === "app" ? "app root" : side + "/"
    const lines = [`### ${edition} · ${where}`, ""]
    const root = collapse(buildTree(shown.map((entry) => entry.slot)))
    const line = (slot: Slot): string => renderSlot(slot, presenceOf.get(slot.id) ?? slot.presence, side, sources, dangling)
    for (const child of root.children.values()) renderNode(child, 0, { lines, line })
    const listed = (ids: readonly string[]): string => ids.map((id) => `\`${id}\``).join(", ")
    const ignored = present.filter((entry) => entry.presence !== "forbidden" && entry.slot.tracked === "ignored").map((entry) => entry.slot.id)
    const refused = present.filter((entry) => entry.presence === "forbidden" || entry.slot.tracked === "external").map((entry) => entry.slot.id)
    lines.push("")
    if (ignored.length > 0) lines.push(`Git-ignored: ${listed(ignored)}.`)
    if (refused.length > 0) lines.push(`Refused (forbidden or external): ${listed(refused)}.`)
    lines.push("")
    return lines
}

/** Renders the generated anatomy block (markers included) from the knowledge tree at `knowledge`. */
export const renderAnatomy = (knowledge: string): AnatomyRender => {
    const sources = readSources(knowledge)
    const dangling = new Set<string>()
    const lines = [BEGIN_MARKER, ""]
    for (const edition of EDITIONS) for (const side of SIDES) lines.push(...renderTree(edition, side, sources, dangling))
    lines.push(END_MARKER)
    return { block: lines.join("\n"), dangling: [...dangling].sort(byCodeUnit) }
}

/** The editions a slice is cut for. */
export const SLICE_EDITIONS: readonly string[] = EDITIONS

/** The sides a slice is cut for: a slice holds the app root and that side. */
export const SLICE_SIDES: readonly string[] = ["be", "fe"]

/** The file of one slice, beside anatomy.md so its links resolve the same: `anatomy-<edition>-<side>.md`. */
export const sliceFile = (edition: string, side: string): string => `anatomy-${edition}-${side}.md`

/** The marker a generated slice carries in place of the anatomy's markers: the whole file is generated. */
export const SLICE_MARKER = "<!-- generated by `starci contexts anatomy --write` from hfs/slots.yaml; do not edit -->"

/**
 * One slice of the anatomy: the app root and one side of one edition, the part a task of that side and edition reads instead
 * of every tree. The whole file is generated; anatomy.md keeps the why and the full tree.
 */
export const renderSlice = (knowledge: string, edition: string, side: string): string => {
    const chosenEdition = EDITIONS.find((item) => item === edition)
    const chosenSide = SIDES.find((item) => item === side && item !== "app")
    if (chosenEdition === undefined || chosenSide === undefined) {
        throw new Refusal("ANATOMY_SLICE_UNKNOWN", `no slice ${edition}/${side}; editions: ${EDITIONS.join(", ")}, sides: ${SLICE_SIDES.join(", ")}`)
    }
    const sources = readSources(knowledge)
    const dangling = new Set<string>()
    const lines = [
        `# Project anatomy: ${chosenEdition}, app root and ${chosenSide}/`,
        "",
        SLICE_MARKER,
        "",
        `The slots of a ${chosenEdition} app at its root and under \`${chosenSide}/\`, cut from [anatomy.md](anatomy.md), which says why the tree`,
        "has this shape and how a line reads: path, slot, presence, the topics that teach it, the rules that judge it.",
        "",
        ...renderTree(chosenEdition, "app", sources, dangling),
        ...renderTree(chosenEdition, chosenSide, sources, dangling),
    ]
    return `${lines.join("\n").trimEnd()}\n`
}

/** Replaces the block between the markers of `text`; refuses when the markers are missing or out of order. */
export const spliceAnatomy = (text: string, block: string, file: string): string => {
    const begin = text.indexOf(BEGIN_MARKER)
    const end = text.indexOf(END_MARKER)
    if (begin < 0 || end < begin) throw new Refusal("ANATOMY_MARKERS_MISSING", `${file} lacks the generated-block markers ${BEGIN_MARKER} … ${END_MARKER}`)
    return text.slice(0, begin) + block + text.slice(end + END_MARKER.length)
}
