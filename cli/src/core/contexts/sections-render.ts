import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { markdownSummary } from "./index-render.js"
import { chunksOf } from "./search-corpus.js"

/** The harness document the section index lists, relative to the runtime root. */
export const SECTIONED_DOC = "cli/README.md"

/** The marker the generated section index carries: the whole file is generated. */
export const SECTIONS_MARKER = "<!-- generated by `starci contexts anatomy --write` from cli/README.md; do not edit -->"

// The title separator of a chunk: the path, then one heading per level.
const TITLE_SEPARATOR = " › "

/**
 * The section index of cli/README.md, or undefined where the tree has none (a fixture of contexts/ alone): one line per
 * heading with its anchor, size and opening sentence, nested by level. A harness worker loads it instead of the whole
 * README and opens a section on demand (`starci contexts anchor <anchor>`), so its fixed context stays inside the code op's
 * budget while every section stays one call away.
 */
export const renderSections = (knowledge: string): string | undefined => {
    const file = join(knowledge, "..", SECTIONED_DOC)
    if (!existsSync(file)) return undefined
    const text = readFileSync(file, "utf8").replaceAll("\r\n", "\n")
    const entries = chunksOf(SECTIONED_DOC, text).flatMap((chunk) => {
        const level = chunk.title.split(TITLE_SEPARATOR).length - 1
        if (level < 1) return []
        const lines = chunk.text.split("\n")
        const heading = (lines[0] ?? "").replace(/^#+\s*/, "")
        const kb = Math.max(1, Math.round(Buffer.byteLength(chunk.text) / 1024))
        const summary = markdownSummary(lines.slice(1))
        const summaryNote = summary === "" ? "" : ` — ${summary}`
        return [`${"  ".repeat(level - 1)}- ${heading} · \`${chunk.anchor}\` · ${String(kb)} KB${summaryNote}`]
    })
    const lines = [
        "# CLI sections",
        "",
        SECTIONS_MARKER,
        "",
        `Every section of [${SECTIONED_DOC}](../../${SECTIONED_DOC}), the owner of how the CLI is built and how the harness inside`,
        "it works, with its anchor, size and the sentence it opens with. A task on the harness itself loads this index",
        "instead of the whole file and reads a section when it needs it: `starci contexts anchor <anchor>` prints one section,",
        '`starci contexts search "<question>" --scope harness` ranks them.',
        "",
        ...entries,
    ]
    return `${lines.join("\n")}\n`
}
