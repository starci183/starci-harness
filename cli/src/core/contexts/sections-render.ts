import { existsSync, readFileSync } from "node:fs"
import { join, posix } from "node:path"
import { markdownSummary } from "./index-render.js"
import type { SectionedDoc } from "./sectioned-docs.js"
import { chunksOf } from "./search-corpus.js"

/** The marker a generated section index carries: the whole file is generated. */
export const sectionsMarker = (doc: SectionedDoc): string => `<!-- generated by \`starci contexts anatomy --write\` from ${doc.source}; do not edit -->`

// The title separator of a chunk: the path, then one heading per level.
const TITLE_SEPARATOR = " › "

/**
 * The section index of one document, or undefined where the tree lacks it (a fixture of contexts/ alone has no cli/README.md):
 * one line per heading with its anchor, size and opening sentence, nested by level.
 */
export const renderSections = (knowledge: string, doc: SectionedDoc): string | undefined => {
    const file = join(knowledge, "..", doc.source)
    if (!existsSync(file)) return undefined
    const text = readFileSync(file, "utf8").replaceAll("\r\n", "\n")
    const entries = chunksOf(doc.source, text).flatMap((chunk) => {
        const level = chunk.title.split(TITLE_SEPARATOR).length - 1
        if (level < 1) return []
        const lines = chunk.text.split("\n")
        const heading = (lines[0] ?? "").replace(/^#+\s*/, "")
        const kb = Math.max(1, Math.round(Buffer.byteLength(chunk.text) / 1024))
        const summary = markdownSummary(lines.slice(1))
        const summaryNote = summary === "" ? "" : ` — ${summary}`
        return [`${"  ".repeat(level - 1)}- ${heading} · \`${chunk.anchor}\` · ${String(kb)} KB${summaryNote}`]
    })
    const link = posix.relative(posix.dirname(`contexts/${doc.index}`), doc.source)
    const lines = [
        `# ${doc.title}`,
        "",
        sectionsMarker(doc),
        "",
        `Every section of [${doc.source}](${link}), the owner of ${doc.owns},`,
        "with its anchor, size and the sentence it opens with. A seat whose op or brief names this index loads it instead of",
        "the whole file and reads a section when it needs it: `starci contexts anchor <anchor>` prints one section,",
        `\`starci contexts search "<question>" --scope ${doc.scope}\` ranks them.`,
        "",
        ...entries,
    ]
    return `${lines.join("\n")}\n`
}
