import { existsSync, readFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { parse } from "yaml"
import { runtimeRoot } from "../../harness/ledger.js"
import { Refusal } from "../../shared/errors.js"

/** The first line of the generated Sonar block of an app's sonar-project.properties. */
export const SONAR_BEGIN = "# starci:sonar-scope begin (generated by `starci app sonar --write` from contexts/hfs/slots.yaml; do not edit)"

/** The last line of the generated Sonar block. */
export const SONAR_END = "# starci:sonar-scope end"

/** The properties file the block lives in, at the app root. */
export const SONAR_FILE = "sonar-project.properties"

/** The slot fields the derivation reads (contexts/hfs/README.md "Slot fields"). */
interface Slot {
    readonly id: string
    readonly profiles: readonly string[]
    readonly path: string
    readonly tracked?: string | undefined
    readonly presence?: string | undefined
    readonly coverage?: string | undefined
    readonly provider?: string | undefined
    readonly requires?: readonly string[] | undefined
    readonly allows?: readonly string[] | undefined
}

/** What an app's hfs.json says that the derivation needs. */
export interface AppFacts {
    readonly edition: "lite" | "full"
    readonly sides: readonly string[]
    readonly providers: readonly string[]
}

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value)

const strings = (value: unknown): string[] | undefined => (Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : undefined)

const text = (value: unknown): string | undefined => (typeof value === "string" ? value : undefined)

const byCodeUnit = (left: string, right: string): number => Number(left > right) - Number(left < right)

/** A slot as it holds under `edition`: undefined when the edition has no such slot; the lite overlay fields win under lite. */
const effectiveSlot = (raw: Record<string, unknown>, edition: string): Slot | undefined => {
    const editions = strings(raw.editions)
    if (editions !== undefined && !editions.includes(edition)) return undefined
    const merged: Record<string, unknown> = edition === "lite" ? { ...raw, ...(isRecord(raw.lite) ? raw.lite : {}), presence: raw.litePresence ?? raw.presence } : raw
    const id = text(merged.id)
    const path = text(merged.path)
    const profiles = strings(merged.profiles)
    if (id === undefined || path === undefined || profiles === undefined) throw new Refusal("SLOTS_INVALID", `a slot of contexts/hfs/slots.yaml lacks id, path or profiles (${id ?? path ?? "?"})`)
    return {
        id,
        path,
        profiles,
        tracked: text(merged.tracked),
        presence: text(merged.presence),
        coverage: text(merged.coverage),
        provider: text(merged.provider),
        requires: strings(merged.requires),
        allows: strings(merged.allows),
    }
}

/** The parsed slot manifest of the harness contexts. */
interface Manifest {
    readonly slots: readonly Record<string, unknown>[]
    readonly be: Record<string, unknown>
}

/** Reads contexts/hfs/slots.yaml of the runtime this CLI belongs to. */
const readManifest = (): Manifest => {
    const file = join(runtimeRoot(), "contexts", "hfs", "slots.yaml")
    if (!existsSync(file)) throw new Refusal("CONTEXTS_NOT_FOUND", `no contexts/hfs/slots.yaml under ${runtimeRoot()}`)
    const parsed: unknown = parse(readFileSync(file, "utf8"))
    if (!isRecord(parsed) || !Array.isArray(parsed.slots) || !isRecord(parsed.ruleParams) || !isRecord(parsed.ruleParams.be)) {
        throw new Refusal("SLOTS_INVALID", `${file} has no slots or ruleParams.be`)
    }
    return { slots: parsed.slots.filter(isRecord), be: parsed.ruleParams.be }
}

/** Every alternative of a pattern's `{a,b}` groups (nested groups included). */
export const braceVariants = (pattern: string): string[] => {
    const open = pattern.indexOf("{")
    if (open === -1) return [pattern]
    let depth = 0
    const cuts: number[] = []
    let close = -1
    for (let at = open; at < pattern.length; at += 1) {
        const char = pattern.charAt(at)
        if (char === "{") depth += 1
        else if (char === "}") {
            depth -= 1
            if (depth === 0) {
                close = at
                break
            }
        } else if (char === "," && depth === 1) cuts.push(at)
    }
    if (close === -1) return [pattern]
    const bounds = [open, ...cuts, close]
    const head = pattern.slice(0, open)
    const tail = pattern.slice(close + 1)
    return bounds.slice(0, -1).flatMap((start, index) => braceVariants(`${head}${pattern.slice(start + 1, bounds[index + 1])}${tail}`))
}

/** The pattern with every `<placeholder>` replaced by `*`. */
const star = (pattern: string): string => pattern.replace(/<[^<>]+>/g, "*")

const isDir = (path: string): boolean => path.endsWith("/")

const segments = (path: string): string[] => path.split("/").filter((segment) => segment !== "")

/** Whether directory pattern `inner` lies inside `outer` or is the same (an outer `*` matches any one segment). */
const nested = (inner: string, outer: string): boolean => {
    const a = segments(inner)
    const b = segments(outer)
    return a.length >= b.length && b.every((segment, index) => segment === "*" || segment === a[index])
}

const dirOf = (path: string): string => (isDir(path) ? path : path.slice(0, path.lastIndexOf("/") + 1))

/** Whether `text` fits `pattern`, where each `*` stands for any run of characters. */
const wildcardMatches = (pattern: string, value: string): boolean => new RegExp("^" + pattern.split("*").map((part) => part.replace(/[.+?^${}()|[\]\\]/g, String.raw`\$&`)).join(".*") + "$").test(value)

/** Whether glob segments `glob` match path-or-glob segments `entry` (`**` crosses directories, `*` stays in one segment). */
const segmentsCover = (glob: readonly string[], entry: readonly string[]): boolean => {
    const [head, ...rest] = glob
    if (head === undefined) return entry.length === 0
    if (head === "**") return Array.from({ length: entry.length + 1 }, (_, skipped) => skipped).some((skipped) => segmentsCover(rest, entry.slice(skipped)))
    const first = entry[0]
    if (first === undefined || first.includes("**")) return false
    return (head.includes("*") ? wildcardMatches(head, first) : head === first) && segmentsCover(rest, entry.slice(1))
}

/** The entries no other entry already covers. */
const withoutCovered = (entries: readonly string[]): string[] =>
    entries.filter((entry) => !entries.some((other) => other !== entry && segmentsCover(other.split("/"), entry.split("/"))))

/** The side-relative path variants of a slot, placeholders as `*`. */
const variantsOf = (slot: Slot): string[] => braceVariants(slot.path).map(star)
/** The fixed non-role `.ts` files the required slots name (their `requires` and `allows`), under each of their directories. */
const fixedFileExclusions = (required: readonly Slot[], suffixes: readonly string[]): string[] => {
    const roleAlternatives = suffixes.map((suffix) => suffix.replace(/[-.]/g, String.raw`\$&`)).join("|")
    const isRole = new RegExp(String.raw`\.(?:${roleAlternatives})\.ts$`)
    return required.flatMap((slot) =>
        [...(slot.requires ?? []), ...(slot.allows ?? [])]
            .filter((entry) => entry.endsWith(".ts") && !entry.includes("<role>"))
            .flatMap((entry) => braceVariants(entry))
            .filter((name) => !isRole.test(star(name).replaceAll("*", "x")))
            .flatMap((name) => variantsOf(slot).map((dir) => `be/${dir}${star(name)}`.replace(/\/\/+/g, "/"))),
    )
}

/**
 * The coverage exclusions of one side: the whole side when it holds no `coverage: required` slot, else (the back end only)
 * every `coverage: none` path, every non-logic suffix and every fixed non-role file a required slot names.
 */
const sideExclusions = (side: string, slots: readonly Slot[], suffixes: readonly string[], roles: readonly string[]): string[] => {
    const own = slots.filter((slot) => slot.profiles.includes(side))
    const required = own.filter((slot) => slot.coverage === "required")
    if (required.length === 0) return [`${side}/**`]
    if (side !== "be") throw new Refusal("SLOTS_INVALID", `side ${side} has coverage: required slots but ruleParams names logic roles for be only`)
    const requiredDirs = required.flatMap((slot) =>
        variantsOf(slot).map((dir) => {
            if (!isDir(dir)) throw new Refusal("SLOTS_INVALID", `slot ${slot.id} is coverage: required but its path ${slot.path} is not a directory`)
            return dir
        }),
    )
    const nonePaths = [...new Set(own.filter((slot) => slot.coverage === "none").flatMap(variantsOf))]
    const swallowing = nonePaths.filter(isDir).find((dir) => requiredDirs.some((other) => nested(other, dir)))
    if (swallowing !== undefined) throw new Refusal("SLOTS_INVALID", `the coverage: none directory ${swallowing} contains a coverage: required slot`)
    const noneMinimal = nonePaths.filter((path) => !nonePaths.some((other) => other !== path && isDir(other) && nested(dirOf(path), other)))
    return [
        ...noneMinimal.map((path) => `be/${path}${isDir(path) ? "**" : ""}`),
        ...suffixes.filter((candidate) => !roles.includes(candidate)).map((suffix) => `be/**/*.${suffix}.ts`),
        ...fixedFileExclusions(required, suffixes),
    ]
}

/**
 * `sonar.coverage.exclusions` of an app, derived from the slots of its edition: the back end's complement of the measured
 * files (a `<name>.<role>.ts` of a `ruleParams.be.logicRoles` role inside a `coverage: required` slot), that is every
 * `coverage: none` path, every non-logic suffix and every fixed non-role file a required slot names; and every declared
 * side that holds no `coverage: required` slot, whole. SonarQube has no coverage inclusions, so the complement is the list.
 */
export const coverageExclusions = (manifest: Manifest, app: AppFacts): string[] => {
    const params: Record<string, unknown> = app.edition === "lite" && isRecord(manifest.be.lite) ? { ...manifest.be, ...manifest.be.lite } : manifest.be
    const suffixes = strings(params.suffixes) ?? []
    const roles = strings(params.logicRoles) ?? []
    const slots = manifest.slots
        .map((raw) => effectiveSlot(raw, app.edition))
        .filter((slot): slot is Slot => slot?.tracked === "tracked" && slot.presence !== "forbidden" && (slot.provider === undefined || app.providers.includes(slot.provider)))
    const result = new Set(app.sides.flatMap((side) => sideExclusions(side, slots, suffixes, roles)))
    return withoutCovered([...result]).sort(byCodeUnit)
}

/** The facts of the app whose hfs.json is in `appRoot`; undefined when it is no app. */
export const appFacts = (appRoot: string): AppFacts | undefined => {
    const file = join(appRoot, "hfs.json")
    if (!existsSync(file)) return undefined
    const parsed: unknown = JSON.parse(readFileSync(file, "utf8"))
    if (!isRecord(parsed) || parsed.kind !== "app") return undefined
    const sides = isRecord(parsed.sides) ? parsed.sides : {}
    const be = isRecord(sides.be) ? sides.be : {}
    const connections = Array.isArray(be.connections) ? be.connections.filter(isRecord) : []
    return {
        edition: parsed.edition === "lite" ? "lite" : "full",
        sides: ["be", "fe"].filter((side) => side in sides),
        providers: [...new Set(connections.flatMap((connection) => (typeof connection.provider === "string" ? [connection.provider] : [])))],
    }
}

/** The generated block of an app, line by line: the begin marker, the derived keys, the end marker. */
export const sonarBlock = (app: AppFacts): string[] => [SONAR_BEGIN, `sonar.coverage.exclusions=${coverageExclusions(readManifest(), app).join(",")}`, SONAR_END]

/** The keys a block sets. */
export const blockKeys = (block: readonly string[]): string[] => block.flatMap((line) => (/^[\w.-]+=/.exec(line) === null ? [] : [line.slice(0, line.indexOf("="))]))

/** Where the block sits in `lines` (begin and end indexes), or undefined; refused when the markers are unpaired. */
export const findBlock = (lines: readonly string[]): { readonly begin: number; readonly end: number } | undefined => {
    const begin = lines.findIndex((line) => line.trimEnd() === SONAR_BEGIN)
    const end = lines.findIndex((line) => line.trimEnd() === SONAR_END)
    if (begin === -1 && end === -1) return undefined
    if (begin === -1 || end < begin) return { begin: Math.max(begin, 0), end: -1 }
    return { begin, end }
}

/** Whether `lines[begin..end]` equals `block` line for line (line endings aside). */
export const blockMatches = (lines: readonly string[], block: readonly string[]): boolean => {
    const found = findBlock(lines)
    if (found === undefined || found.end === -1 || found.end - found.begin + 1 !== block.length) return false
    return block.every((line, index) => (lines[found.begin + index] ?? "").replace(/\r$/, "") === line)
}

/**
 * The file text with the block in place: the old block replaced, else the first line of a key the block sets replaced
 * by it, else appended. Every other line setting a key the block sets is dropped, so the generated value is the one Sonar reads.
 */
export const spliceBlock = (textOfFile: string, block: readonly string[]): string => {
    const lines = textOfFile.replaceAll("\r\n", "\n").replace(/\n$/, "").split("\n")
    const found = findBlock(lines)
    const kept = found !== undefined && found.end !== -1 ? [...lines.slice(0, found.begin), "\u0000", ...lines.slice(found.end + 1)] : lines.filter((line) => line.trimEnd() !== SONAR_BEGIN && line.trimEnd() !== SONAR_END)
    const keys = blockKeys(block)
    const out: string[] = []
    let placed = false
    for (const line of kept) {
        const key = /^\s*([\w.-]+)\s*[=:]/.exec(line)?.[1]
        if (line === "\u0000" || (key !== undefined && keys.includes(key))) {
            if (!placed) out.push(...block)
            placed = true
        } else out.push(line)
    }
    if (!placed) out.push(...block)
    return `${out.join("\n")}\n`
}

/** The app root a repository file belongs to: the nearest directory at or above it, inside `root`, holding an app hfs.json. */
export const appRootOf = (root: string, file: string): string | undefined => {
    const top = resolve(root)
    let directory = dirname(resolve(top, file))
    for (;;) {
        if (appFacts(directory) !== undefined) return directory
        if (directory === top || dirname(directory) === directory || !directory.startsWith(top)) return undefined
        directory = dirname(directory)
    }
}
