// gen-catalog.mjs - writes packages/cli/src/catalog.generated.mjs, the command table the documentation check judges a `starci ...` text against
// (scripts/hfs/doc-commands.mjs checkCommand; rules/doc-fresh.mjs HFS_DOC_COMMAND_UNKNOWN), from the one owner of every verb: the registry of
// the starci CLI (cli/src/registry.ts ALL_VERBS, built to cli/dist/registry.js). Run it from the harness repository after the CLI is built:
//   node packages/hfs/runtime/scripts/cli/gen-catalog.mjs [--registry <registry.js>] [--check]
// --check writes nothing and exits 1 when the committed catalog differs from the registry's.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { isMain } from '../lib/is-main.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const CATALOG_FILE = path.resolve(HERE, '../../packages/cli/src/catalog.generated.mjs');
const DEFAULT_REGISTRY = path.resolve(HERE, '../../../../../cli/dist/registry.js');

/** The options the program itself takes before any verb (cli/src/main.ts buildProgram), plus commander's --help. */
const GLOBAL = [
  { name: 'json', type: 'boolean', summary: 'print one json envelope instead of human text' },
  { name: 'cwd', type: 'string', summary: 'run as if started in this directory' },
  { name: 'help', type: 'boolean', summary: 'print the help of the command' },
];

const TYPES = { boolean: 'boolean', string: 'string', list: 'list' };

/** One registry verb as the catalog entry validate-args.mjs reads: its options, its positional slots in order, its editions. */
function entryOf(verb) {
  const specs = Object.entries(verb.flags);
  return {
    summary: verb.summary,
    flags: specs.filter(([, spec]) => spec.positional !== true && spec.kind !== 'rest')
      .map(([name, spec]) => ({ name, type: TYPES[spec.kind], summary: spec.summary, ...(spec.required === true ? { required: true } : {}) })),
    positional: specs.filter(([, spec]) => spec.positional === true || spec.kind === 'rest')
      .map(([name, spec]) => ({ name, required: spec.required === true, variadic: spec.kind === 'rest' })),
    editions: [...verb.editions],
    json: 'flag',
  };
}

/** The catalog of `verbs`: a two-word verb under its group, a one-word verb (`starci explain [term]`) as the group's `self`. */
export function catalogOf(verbs) {
  const groups = {};
  for (const verb of verbs) {
    const [group, name] = verb.path;
    groups[group] ??= { verbs: {} };
    if (name === undefined) groups[group].self = entryOf(verb);
    else groups[group].verbs[name] = entryOf(verb);
  }
  return { schema: 'starci/cli-catalog@2', global: GLOBAL, groups };
}

export const catalogText = (catalog) => `// GENERATED by runtime/scripts/cli/gen-catalog.mjs from the starci CLI registry (cli/src/registry.ts) - do not edit
export const CATALOG = ${JSON.stringify(catalog, null, 2)};
`;

async function main(argv) {
  const at = argv.indexOf('--registry');
  const registry = at >= 0 ? path.resolve(argv[at + 1] ?? '') : DEFAULT_REGISTRY;
  const { ALL_VERBS } = await import(pathToFileURL(registry).href);
  const text = catalogText(catalogOf(ALL_VERBS));
  if (argv.includes('--check')) {
    const same = fs.existsSync(CATALOG_FILE) && fs.readFileSync(CATALOG_FILE, 'utf8') === text;
    process.stdout.write(same ? 'catalog.generated.mjs matches the registry\n' : 'catalog.generated.mjs differs from the registry: run gen-catalog.mjs\n');
    return same ? 0 : 1;
  }
  fs.writeFileSync(CATALOG_FILE, text);
  process.stdout.write(`wrote ${path.relative(process.cwd(), CATALOG_FILE)} (${ALL_VERBS.length} verbs)\n`);
  return 0;
}

if (isMain(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
