/**
 * Regenerates `vocabulary.generated.ts` from the grammar CSS snapshot in `fixtures/grammar/src` and HeroUI's theme in
 * `fixtures/heroui/variables.css`: `npm run vocabulary`. `npm run vocabulary -- <grammar package>/src` first refreshes
 * both snapshots from a grammar checkout (the files GRAMMAR_CSS lists, and the `variables.css` of the `@heroui/styles`
 * it installs), so the generated lists and the spec read the same bytes.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { extractVocabulary, GRAMMAR_CSS, HEROUI_VARIABLES } from "./extract-vocabulary.ts"

const here = path.dirname(fileURLToPath(import.meta.url))
const grammarSrc = path.resolve(here, "../../fixtures/grammar/src")
const heroVariables = path.resolve(here, "../..", HEROUI_VARIABLES)
const source = process.argv[2]
if (source) {
  for (const file of GRAMMAR_CSS) {
    fs.mkdirSync(path.dirname(path.join(grammarSrc, file)), { recursive: true })
    fs.copyFileSync(path.resolve(source, file), path.join(grammarSrc, file))
  }
  fs.mkdirSync(path.dirname(heroVariables), { recursive: true })
  fs.copyFileSync(path.resolve(source, "../node_modules/@heroui/styles/dist/themes/default/variables.css"), heroVariables)
}
const { declared, vendor, breakpoints, statusTones } = extractVocabulary(grammarSrc, heroVariables)
const list = (names: readonly string[]): string => names.map((name) => `  ${JSON.stringify(name)},`).join("\n")
fs.writeFileSync(
  path.join(here, "vocabulary.generated.ts"),
  `// Generated by src/lib/write-vocabulary.ts from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** Un-prefixed custom properties: HeroUI's theme, the component-local ones the grammar declares and the soft pair of every status tone. */\nexport const DECLARED: readonly string[] = [\n${list(declared)}\n]\n\n` +
    `/** Un-prefixed custom properties the grammar reads but a vendor layer declares. */\nexport const VENDOR: readonly string[] = [\n${list(vendor)}\n]\n\n` +
    `/** Width breakpoints of the grammar's media queries, ascending. */\nexport const BREAKPOINTS: readonly string[] = [\n${list(breakpoints)}\n]\n\n` +
    `/** The status tones: each has a solid pair and a soft pair, in light and in dark. */\nexport const STATUS_TONES: readonly string[] = [\n${list(statusTones)}\n]\n`,
)
// The core Grammar lint judges class names against the same tone list, so this generator writes its copy too.
fs.writeFileSync(
  path.resolve(here, "../../../eslint-grammar-core/src/lib/status-tones.generated.ts"),
  `// Generated by packages/stylelint-canon/src/lib/write-vocabulary.ts from packages/grammar/src. Do not edit: run \`npm run vocabulary\` in packages/stylelint-canon.\n\n` +
    `/** The status tones of the grammar: each has a solid pair and a soft pair (\`--<tone>-soft\`, \`--<tone>-soft-foreground\`). */\nexport const STATUS_TONES: readonly string[] = [\n${list(statusTones)}\n]\n`,
)
console.log(`vocabulary.generated.ts: ${declared.length} declared, ${vendor.length} vendor, ${breakpoints.length} breakpoints, ${statusTones.length} status tones; eslint-grammar-core status-tones.generated.ts`)
