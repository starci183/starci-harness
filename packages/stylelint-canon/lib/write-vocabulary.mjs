/**
 * Regenerates `vocabulary.generated.mjs` and `grammar-values.generated.mjs` from the grammar CSS snapshot in
 * `fixtures/grammar/src`: `npm run vocabulary`. `npm run vocabulary -- <grammar package>/src` first refreshes that snapshot
 * from a grammar checkout (only the files GRAMMAR_CSS lists), so the generated lists and the spec read the same bytes.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { extractValues } from "./extract-values.mjs"
import { extractVocabulary, GRAMMAR_CSS } from "./extract-vocabulary.mjs"

const here = path.dirname(fileURLToPath(import.meta.url))
const grammarSrc = path.resolve(here, "../fixtures/grammar/src")
const source = process.argv[2]
if (source) {
  for (const file of GRAMMAR_CSS) {
    fs.mkdirSync(path.dirname(path.join(grammarSrc, file)), { recursive: true })
    fs.copyFileSync(path.resolve(source, file), path.join(grammarSrc, file))
  }
}
const { declared, vendor, breakpoints, statusTones } = extractVocabulary(grammarSrc)
const list = (names) => names.map((name) => `  ${JSON.stringify(name)},`).join("\n")
fs.writeFileSync(
  path.join(here, "vocabulary.generated.mjs"),
  `// Generated by lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** Un-prefixed custom properties the grammar declares (and the soft pair of every status tone). */\nexport const DECLARED = [\n${list(declared)}\n]\n\n` +
    `/** Un-prefixed custom properties the grammar reads but a vendor layer declares. */\nexport const VENDOR = [\n${list(vendor)}\n]\n\n` +
    `/** Width breakpoints of the grammar's media queries, ascending. */\nexport const BREAKPOINTS = [\n${list(breakpoints)}\n]\n\n` +
    `/** The status tones: each has a solid pair and a soft pair, in light and in dark. */\nexport const STATUS_TONES = [\n${list(statusTones)}\n]\n`,
)
const values = extractValues(grammarSrc)
fs.writeFileSync(
  path.join(here, "grammar-values.generated.mjs"),
  `// Generated by lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** The custom properties the grammar declares on its theme roots, per theme and family (\`common\` is the root every family sits on). */\n` +
    `export const GRAMMAR_VALUES = ${JSON.stringify(values, null, 2)}\n`,
)
console.log(`vocabulary.generated.mjs: ${declared.length} declared, ${vendor.length} vendor, ${breakpoints.length} breakpoints, ${statusTones.length} status tones; grammar-values.generated.mjs`)
